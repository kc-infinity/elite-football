import fs from 'fs';
import path from 'path';

// Load existing gameDatabase.ts
const gameDbPath = path.resolve('src/data/gameDatabase.ts');
const gameDbContent = fs.readFileSync(gameDbPath, 'utf8');

// Extract the existing PLAYERS_DB array
const match = gameDbContent.match(/export const PLAYERS_DB: FootballPlayer\[\] = (\[[\s\S]*?\n\]);/);
if (!match) {
  console.error("Could not find PLAYERS_DB in gameDatabase.ts");
  process.exit(1);
}

// Evaluate existing players safely
