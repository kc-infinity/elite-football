// Helper to pick pseudo-random name cleanly
function pickRandomName(seed: number, pos: PositionCode): { name: string; nat: string; club: string } {
  const natIdx = (seed * 17 + 23) % PRO_NATIONS.length;
  const nat = PRO_NATIONS[natIdx];
  const clubIdx = (seed * 31 + 47) % PRO_CLUBS.length;
  const club = PRO_CLUBS[clubIdx];

  let bankKey = 'european';
  if (["Brazil", "Portugal"].includes(nat)) bankKey = 'latin';
  else if (["Spain", "Argentina", "Uruguay", "Colombia", "Chile", "Ecuador", "Paraguay", "Peru", "Mexico", "Costa Rica"].includes(nat)) bankKey = 'hispanic';
  else if (["Croatia", "Serbia", "Poland", "Czech Republic", "Slovakia", "Slovenia", "Bosnia", "Montenegro", "Ukraine", "Romania", "Hungary"].includes(nat)) bankKey = 'slavic_balkan';
  else if (["Nigeria", "Senegal", "Ghana", "Ivory Coast", "Cameroon", "Mali", "Guinea", "Morocco", "Egypt", "Algeria"].includes(nat)) bankKey = 'african';
  else if (["Japan", "South Korea"].includes(nat)) bankKey = 'asian';

  const surnames = SURNAME_BANKS[bankKey] || SURNAME_BANKS.european;
  const fn = FIRST_NAMES[(seed * 13 + 7) % FIRST_NAMES.length];
  const sn = surnames[(seed * 19 + 11) % surnames.length];

  return { name: `${fn} ${sn}`, nat, club };
}

